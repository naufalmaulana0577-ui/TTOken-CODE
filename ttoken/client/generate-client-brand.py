"""Bangun wordmark TTOken Code untuk klien dan mask indikator berjalan."""
import sys
sys.argv = [sys.argv[0], sys.argv[1], sys.argv[2]]
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from PIL import Image, ImageDraw

font_path, out = sys.argv[1], sys.argv[2]

def outline(text, weight, size, tracking, x0, baseline):
    font = TTFont(font_path)
    axes = {a.axisTag: a.defaultValue for a in font['fvar'].axes}
    axes['wght'] = weight
    if 'opsz' in axes: axes['opsz'] = 48
    font = instantiateVariableFont(font, axes)
    glyphs, cmap, upm = font.getGlyphSet(), font.getBestCmap(), font['head'].unitsPerEm
    scale, x, parts = size / upm, x0, []
    for ch in text:
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs, ntos=lambda v: f'{v:.2f}'.rstrip('0').rstrip('.'))
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
        d = pen.getCommands()
        if d: parts.append(d)
        x += glyphs[name].width * scale + tracking * size
    return ' '.join(parts), x - tracking * size

def rr(x, y, w, h, r):
    return (f'M{x + r} {y}H{x + w - r}A{r} {r} 0 0 1 {x + w} {y + r}V{y + h - r}A{r} {r} 0 0 1 {x + w - r} {y + h}'
            f'H{x + r}A{r} {r} 0 0 1 {x} {y + h - r}V{y + r}A{r} {r} 0 0 1 {x + r} {y}Z')

# Mark pada tinggi 24 (skala 0,5 dari geometri 56x48).
body = rr(0, 0, 28, 8, 4) + rr(3, 2, 9, 22, 4.5) + rr(16, 2, 9, 13, 4.5)
bar = rr(16, 18.5, 9, 4, 2)
TEXT_X = 36
a, xa = outline('TTOken', 600, 19, -0.03, TEXT_X, 18.6)
b, xb = outline('Code', 400, 19, -0.02, xa + 5.3, 18.6)
full = int(round(xb + 0.5))
name_only = full - TEXT_X

tsx = f'''import type {{ IconProps }} from './icons/props.ts'

/** Display options for the TTOken Code brand wordmark. */
export interface BrandWordmarkProps extends IconProps {{
  /** Whether to include the leading mark; defaults to true. */
  includeMark?: boolean | undefined
}}

/**
 * Render the TTOken Code wordmark. Generated by ttoken/installer/generate-brand-assets.py; do not edit by hand.
 * @param props.size - height in px (default 24; width follows the selected artwork).
 * @param props.className - extra class for layout placement.
 * @param props.includeMark - whether to include the leading mark.
 * @returns the wordmark svg (aria-hidden decorative brand art).
 */
export function BrandWordmark({{ size = 24, className, includeMark = true }}: BrandWordmarkProps) {{
  const width = includeMark ? {full} : {name_only}
  return (
    <svg
      width={{(size * width) / 24}}
      height={{size}}
      className={{className}}
      viewBox={{includeMark ? '0 0 {full} 24' : '{TEXT_X} 0 {name_only} 24'}}
      fill="none"
      aria-hidden="true"
    >
      {{includeMark && <path d="{body}" fill="#FFB21A" />}}
      {{includeMark && <path d="{bar}" fill="currentColor" />}}
      <path d="{a}" fill="currentColor" />
      <path d="{b}" fill="currentColor" fillOpacity="0.72" />
    </svg>
  )
}}
'''
open(f'{out}/BrandWordmark.tsx', 'w', encoding='utf8').write(tsx)

# Mask indikator berjalan: siluet mark 28x28, kanal alfa sebagai bentuk.
S = 8
im = Image.new('L', (28 * S, 28 * S), 0)
d = ImageDraw.Draw(im)
k = 28 * S / 56
oy = (28 * S - 48 * k) / 2
for x, y, w, h, r in [(0, 0, 56, 16, 8), (6, 4, 18, 44, 9), (32, 4, 18, 26, 9), (32, 37, 18, 8, 4)]:
    d.rounded_rectangle([x * k, oy + y * k, (x + w) * k, oy + (y + h) * k], radius=r * k, fill=255)
alpha = im.resize((28, 28), Image.LANCZOS)
mask = Image.merge('LA', (Image.new('L', (28, 28), 0), alpha))
mask.save(f'{out}/running-mark@2x.png')
print('wordmark lebar', full, '| tanpa mark', name_only)
